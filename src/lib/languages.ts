/** Google Fonts weight spec per family (requesting an unavailable weight makes the API reject the whole URL). */
const FONT_WEIGHTS: Record<string, string> = {
  "Great Vibes": "",
  Amiri: "wght@400;700",
  "Playfair Display": "ital,wght@0,400;0,700;1,400",
  "Cormorant Garamond": "ital,wght@0,400;0,600;1,400",
  Cinzel: "wght@400;700",
  "EB Garamond": "ital,wght@0,400;0,600;1,400",
  Lato: "wght@400;700",
  Montserrat: "wght@400;600",
  Raleway: "wght@400;600",
  "DM Serif Display": "",
  "DM Sans": "wght@400;600",
  "Libre Baskerville": "ital,wght@0,400;0,700;1,400",
  "Josefin Sans": "wght@400;600",
  Fraunces: "wght@400;700",
  Nunito: "wght@400;700",
};

/** Google Fonts stylesheet URL for the fonts a card needs. */
export function googleFontsHref(families: string[]): string {
  const unique = Array.from(new Set(families.filter(Boolean)));
  if (!unique.length) return "";
  const parts = unique.map((f) => {
    const spec = f in FONT_WEIGHTS ? FONT_WEIGHTS[f] : "wght@400;700";
    return `family=${f.replace(/ /g, "+")}${spec ? ":" + spec : ""}`;
  });
  return `https://fonts.googleapis.com/css2?${parts.join("&")}&display=swap`;
}
